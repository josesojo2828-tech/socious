const prisma = new PrismaClient();

async function SeedExchangeList() {
  const seen = new Set<string>();
  const createData: Prisma.FoodExchangeListCreateInput[] = [];
  for (const item of list) {
    // `name` is unique, so the first entry for a name is the one that lands in
    // the database (`createMany({ skipDuplicates })` drops the rest). Keep the
    // same winner here so the update pass below does not disagree with it.
    if (seen.has(item.name)) continue;
    seen.add(item.name);

    const category = item.category || "GENERAL";
    const sub = item.sub.toString();

    createData.push({
      name: item.name,
      unity: item.unity.toString(),
      grams: item.grams ?? null,
      calories: Number(item.caloria) || 0,
      category,
      sub,
      // Must be derived from the values actually persisted above, not from the
      // raw fixture: the SQL backfill in the migration reads the stored columns,
      // so both paths have to produce the same folded text.
      searchText: normalizeSearchText(item.name, category, sub),
    });
  }

  await prisma.$transaction(
    async (tx) => {
      await tx.foodExchangeList.createMany({
        data: createData,
        skipDuplicates: true,
      });

      // `skipDuplicates` skips rows that already exist instead of updating them,
      // so a database seeded by an older fixture would never receive `grams` nor
      // the corrected `calories`. Re-apply the fixture values so every run
      // converges on the same state. `name` is never rewritten here: it is the
      // unique key that existing ExchangeListItem rows point at.
      for (const row of createData) {
        await tx.foodExchangeList.updateMany({
          where: { name: row.name },
          data: {
            unity: row.unity,
            grams: row.grams,
            calories: row.calories,
            category: row.category,
            sub: row.sub,
            searchText: row.searchText,
          },
        });
      }

      // The fixture is the full catalog: any row whose name it no longer knows
      // is an orphan from an older seed. Delete them so the table converges on
      // the fixture (the DB guard asserts exact set equality). The FK from
      // ExchangeListItem is ON DELETE SET NULL, so lists that referenced an
      // orphan keep their rows with a null food instead of failing the seed.
      await tx.foodExchangeList.deleteMany({
        where: { name: { notIn: createData.map((row) => row.name) } },
      });
    },
    // 255 sequential updateMany calls exceed Prisma's default 5s interactive
    // transaction timeout. 30s is generous and safe for production.
    { timeout: 30_000 },
  );

  console.log("✅ Carga de Listas de Intercambio finalizada.");
}

// Only run when this file is the process entry point, so tests can import the
// fixture data without firing a database write.
if (require.main === module) {
  SeedExchangeList();
}
